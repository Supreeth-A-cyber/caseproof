
from datetime import datetime, timezone
from pathlib import Path


def generate_report(case_data, mapped_claims, gaps, audit_metadata):
    """
    Generate an explainable Markdown investigation report.
    """

    case_id = case_data.get("case_id", "UNKNOWN")
    case_title = case_data.get("case_title", "Untitled Case")

    report_lines = [
    f"# Investigation Report: {case_title}",
    "",
    f"**Case ID:** {case_id}",
    f"**Investigation Run ID:** {audit_metadata['run_id']}",
    f"**Generated:** {audit_metadata['generated_at']}",
    f"**Audit Version:** {audit_metadata['audit_version']}",
        "",
        "## 1. Investigation Summary",
        "",
        f"- Total evidence records: {len(case_data['evidence'])}",
        f"- Total analyst claims: {len(mapped_claims)}",
        f"- Evidence gaps identified: {len(gaps)}",
        "",
        "## 2. Evidence Inventory",
        ""
    ]

    for evidence in case_data["evidence"]:
        report_lines.extend([
            f"### {evidence.get('evidence_id', 'UNKNOWN')}",
            f"- Event type: {evidence.get('event_type', 'Unknown')}",
            f"- Username: {evidence.get('username', 'Unknown')}",
            f"- Source IP: {evidence.get('source_ip', 'Unknown')}",
            ""
        ])

    report_lines.extend([
        "## 3. Claim Validation Results",
        ""
    ])

    for claim in mapped_claims:

        validation = claim.get("validation_details", {})

        report_lines.extend([
            f"### {claim['claim_id']}",
            f"**Statement:** {claim['statement']}",
            f"**Assessment:** {claim.get('validation_result', 'Not assessed')}",
            f"**Reason:** {claim.get('validation_reason', 'No explanation available.')}",
            f"**Referenced evidence:** {', '.join(claim['evidence_ids']) or 'None'}",
            f"**Evidence count:** {validation.get('evidence_count', len(claim.get('linked_evidence', [])))}",
        ])

        if "expected_count" in validation:
            report_lines.extend([
                f"**Expected failed login count:** {validation['expected_count']}",
                f"**Observed failed login count:** {validation['actual_count']}"
            ])

        report_lines.append("")

    report_lines.extend([
        "## 4. Evidence Gaps",
        ""
    ])

    if gaps:
        for gap in gaps:
            report_lines.append(f"### {gap['claim_id']}")
            report_lines.append(f"**Claim:** {gap['statement']}")

            for requirement in gap["missing_requirements"]:
                report_lines.append(f"- Missing: {requirement}")

            report_lines.append("")
    else:
        report_lines.append("No evidence gaps identified.")

    report_lines.extend([
        "## 5. Investigation Limitations",
        "",
        "- Assessments are based only on supplied evidence.",
        "- Missing evidence does not prove that an event did not occur.",
        "- Automated results require analyst review.",
        "- Claim assessments are rule-based and limited to implemented claim types.",
        "",
        "---",
        "*Generated by CaseProof — SOC Investigation Evidence Auditor*"
    ])

    report_content = "\n".join(report_lines)

    reports_directory = Path("reports")
    reports_directory.mkdir(parents=True, exist_ok=True)

    report_path = reports_directory / f"{case_id}_report.md"

    report_path.write_text(report_content, encoding="utf-8")

    print(f"\nInvestigation report generated: {report_path}")
